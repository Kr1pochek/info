export function translateAdminText(value, language) {
  return language === 'kz' ? (kk[value] || value) : value;
}

export function useAdminI18n() {
  const { language, setLanguage } = useLanguage();
  const tr = useCallback((ru, kz = kk[ru]) => language === 'kz' ? (kz || ru) : ru, [language]);
  return useMemo(() => ({
    language,
    locale: language === 'kz' ? 'kk-KZ' : 'ru-RU',
    tr,
    toggleLanguage: () => setLanguage(language === 'kz' ? 'ru' : 'kz', true),
    localized: (item, ruKey, kzKey) => item?.[language === 'kz' ? kzKey : ruKey],
  }), [language, setLanguage, tr]);
}
